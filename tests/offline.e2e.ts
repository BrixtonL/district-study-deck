import { test, expect } from '@playwright/test';
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { zipSync } from 'fflate';
const pack = process.env.STUDY_PACK_DIR || path.resolve('..');
test('private import, directory, every quiz mode, offline cold reload and local deletion', async ({ page, context }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  const contents: Record<string, Uint8Array> = { 'District_Study_Deck.xlsx': new Uint8Array(await readFile(path.join(pack, 'District_Study_Deck.xlsx'))) };
  for (const f of await readdir(path.join(pack, 'photos'))) contents[`photos/${f}`] = new Uint8Array(await readFile(path.join(pack, 'photos', f)));
  const zip = Buffer.from(zipSync(contents));
  await page.goto('./');
  await expect(page.getByText('Ready for offline', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Know your district.' })).toBeVisible();
  const appURL = new URL('./', page.url());
  const manifestLink = await page.locator('link[rel="manifest"]').getAttribute('href');
  const manifestResponse = await page.request.get(new URL(manifestLink!, appURL).href);
  expect(manifestResponse.ok()).toBe(true);
  const manifest = await manifestResponse.json();
  expect(manifest.id).toBe(appURL.pathname);
  expect(manifest.scope).toBe(appURL.pathname);
  expect(manifest.start_url).toBe(appURL.pathname);
  expect(await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)).toBe(appURL.href);
  await page.screenshot({ path: testInfo.outputPath('desktop-preview.png'), fullPage: true });
  // Prove the first import works offline, before the lazy importer is requested by the page.
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByText('Offline · ready')).toBeVisible();
  await page.getByRole('button', { name: 'Study data', exact: true }).click();
  await page.getByLabel('Choose study pack ZIP').setInputFiles({ name: 'fictional-study-pack.zip', mimeType: 'application/zip', buffer: zip });
  await expect(page.getByLabel('Import preview')).toContainText('4 fictional people');
  await page.getByRole('button', { name: 'Import and save deck' }).click();
  await expect(page.getByText('Study pack imported.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'People directory', exact: true }).click();
  await expect(page.locator('.person-card')).toHaveCount(4);
  const name = await page.locator('.person-card h2').first().innerText();
  await page.getByRole('textbox', { name: 'Search people' }).fill(name);
  await expect(page.locator('.person-card')).toHaveCount(1);
  await page.getByRole('textbox', { name: 'Search people' }).fill('unmatched-search');
  await expect(page.getByText('No matching people')).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await expect(page.locator('.person-card')).toHaveCount(4);
  expect(await page.locator('.person-card img').evaluateAll(imgs => imgs.every(img => (img as HTMLImageElement).naturalWidth > 0))).toBe(true);
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByText('Offline · ready')).toBeVisible();
  await page.getByRole('button', { name: 'People directory', exact: true }).click();
  await expect(page.locator('.person-card')).toHaveCount(4);
  await page.setViewportSize({ width: 390, height: 844 });
  const overflow = await page.evaluate(() => Array.from(document.querySelectorAll('body *')).filter(el => el.getBoundingClientRect().right > innerWidth + 1).map(el => ({ tag: el.tagName, class: el.className })).slice(0, 8));
  expect(overflow).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath('mobile-directory.png'), fullPage: true });
  for (const mode of ['Photo to name', 'Name to photo', 'Know their role', 'District knowledge']) {
    await page.getByRole('button', { name: 'Practice', exact: true }).click();
    await page.getByRole('button', { name: new RegExp(mode) }).click();
    await expect(page.locator('.choice')).toHaveCount(4);
    const choices = await page.locator('.choice').allTextContents();
    await page.locator('.choice').first().click();
    await expect(page.locator('.feedback')).toBeVisible();
    await page.reload();
    await page.getByRole('button', { name: 'Resume practice', exact: true }).click();
    await expect(page.locator('.feedback')).toBeVisible();
    if (mode !== 'Name to photo') expect(await page.locator('.choice').allTextContents()).toEqual(choices);
    await page.getByRole('button', { name: 'Next question' }).click();
    await expect(page.getByText(/Question 2 of/)).toBeVisible();
  }
  await page.getByRole('button', { name: 'My progress', exact: true }).click();
  await expect(page.getByText('Questions answered')).toBeVisible();
  await expect(page.locator('.stats-row strong').first()).toHaveText('4');
  await page.getByRole('button', { name: 'Study data', exact: true }).click();
  // The lazy Excel parser was never needed from the network after cache installation.
  await page.getByLabel('Choose study pack ZIP').setInputFiles({ name: 'offline-pack.zip', mimeType: 'application/zip', buffer: zip });
  await expect(page.getByLabel('Import preview')).toContainText('16 custom questions');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Remove local data' }).click();
  await page.getByRole('button', { name: 'Keep my data' }).click();
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Remove local data' }).click();
  await page.getByRole('button', { name: 'Delete local data', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'People directory', exact: true }).click();
  await expect(page.getByText('Your people will appear here')).toBeVisible();
  expect(errors).toEqual([]);
});
